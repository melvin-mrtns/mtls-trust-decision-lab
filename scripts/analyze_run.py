def detect_expired_client_cert_case(out_dir: Path) -> Optional[Dict[str, Any]]:
    """
    Detects: ValidityWindowFailure > ExpiredCertificateCase
    Direction: server verifies client
    Deterministic: No (log-based with fallback to datetime comparison)
    Evidence: server/error.log OR certs/fields/client_cert.txt + server/nginx_time_utc.txt
    """
    archetype = "ValidityWindowFailure"
    case = "ExpiredCertificateCase"
    metadata = get_case_metadata(archetype, case)

    error_log = read_text(out_dir, "server/error.log")
    signal = first_regex_match(error_log, metadata["signals"])
    if signal:
        return build_failure_result(
            archetype,
            case,
            evidence_file="server/error.log",
            failure_signal=signal,
            verifier="server",
            is_deterministic=False
        )

    # Fallback: datetime comparison
    now_utc = verify_time_utc(out_dir)
    not_before, not_after = parse_notbefore_notafter(read_text(out_dir, "certs/fields/client_cert.txt"))

    if now_utc and not_after and now_utc > not_after:
        signal = f"now={now_utc.isoformat()} > notAfter={not_after.isoformat()}"
        return build_failure_result(
            archetype,
            case,
            evidence_file="certs/fields/client_cert.txt + server/nginx_time_utc.txt",
            failure_signal=signal,
            verifier="server",
        is_deterministic=False
        )

    return None


