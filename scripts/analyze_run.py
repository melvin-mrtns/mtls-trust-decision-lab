# ===== BASELINE SUCCESS =====
def check_request_accepted(out_dir: Path) -> bool:
    """
    Check if the request actually reached Flask, regardless of verification failures.
    This is used to distinguish hard failures from soft-fail warnings.
    Evidence:
      - server/flask_container_logs_since_run.txt contains request handling lines.
    """
    flask_logs = read_text(out_dir, "server/flask_container_logs_since_run.txt")
    return bool(re.search(r'"(GET|POST|PUT|DELETE)\s+/', flask_logs, flags=re.IGNORECASE))


# ===== ANALYZER ORCHESTRATION =====
def analyze(out_dir: Path) -> Dict[str, Any]:
    """
    Analyzer follows the trust decision graph model (see docs/trust-decision-graph.md)

    The analyzer checks for verification failures first, then checks if the request
    was accepted despite the failure (soft-fail/warning) or rejected (hard failure).
    """
    detectors = [
        # Step 1 - Peer Certificate Presentation
        detect_missing_client_certificate_case,

        # Step 2 - Trust Anchor Resolution
        detect_untrusted_self_signed_leaf_case,
        detect_wrong_trust_anchor_server_cert_case,
        detect_wrong_trust_anchor_client_cert_case,

        # Step 3 - Path Building
        detect_missing_intermediate_server_cert_case,
        detect_missing_intermediate_client_cert_case,

        # Step 4 - Proof of Possession
        detect_certificateverify_signature_mismatch_case,

        # Step 5 - Time Validity
        detect_expired_server_cert_case,
        detect_expired_client_cert_case,
        detect_not_yet_valid_server_cert_case,
        detect_not_yet_valid_client_cert_case,

        # Step 6 - Usage Constraints
        detect_extended_key_usage_constraint_case,
        detect_basic_constraints_violation_case,

        # Step 7 — Identity Binding
        detect_dns_san_mismatch_case,
    ]

    # Check if request was accepted (reached Flask)
    request_accepted = check_request_accepted(out_dir)

    # Try to detect verification failures
    for detector in detectors:
        result = detector(out_dir)
        if result:
            # Verification failure detected but request was accepted: downgrade to soft-fail warning.
            if request_accepted:
                result["warning"] = True
                result["status"] = "ACCEPT"
                result["symptom"] = f"WARNING: {result['symptom']} However, request was accepted (soft-fail configuration)."
            return result

    # No verification failures detected: check if request succeeded
    if request_accepted:
        return build_success_result(
            evidence_file="server/flask_container_logs_since_run.txt",
            success_signal="Flask logs show request handling (request reached Flask).",
        )

    return build_unknown_result(out_dir)


# ===== OUTPUT FORMATTING =====
def format_result_text(result: Dict[str, Any]) -> str:
    """
    Render a readable terminal and text-file summary
    """
    status = result.get("status")
    warning = result.get("warning")

    if status == "ACCEPT" and warning:
        display_status = "WARNING (soft-fail: verification failed but request accepted)"
    elif status == "ACCEPT":
        display_status = "SUCCESS"
    else:
        display_status = "FAILURE"

    step_block = ""
    if result.get("decision_step"):
        step = result["decision_step"]
        step_block = (
            f"Step:          {step['step_id']} — {step['step_name']}\n"
            f"Decision:      {step['decision']}\n"
            f"Failing input: {result.get('failing_input', '')}\n"
        )


    return (
        "----------Run Analysis----------\n"
        f"Result:       {display_status}\n"
        f"Archetype:    {result.get('archetype', '')}\n"
        f"Case:         {result.get('case', '')}\n"
        f"{step_block}"
        f"Detected by:  {result.get('detected_by', '')}\n"
        "\n"
        "Evidence:\n"
        f"  file:   {result.get('evidence_file', '')}\n"
        f"  signal: {result.get('failure_signal', '')}\n"
        "\n"
        "Symptom:\n"
        f"  {result.get('symptom', '')}\n"
        "\n"
        "Minimal fix:\n"
        f"  {result.get('minimal_fix', '')}\n"
    )


def write_outputs(out_dir: Path, result: Dict[str, Any]) -> None:
    """
    Persist analysis outputs along with the evidence dir in:
      - result.json
      - result.txt
    """
    (out_dir / "result.json").write_text(json.dumps(result, indent=2))
    (out_dir / "result.txt").write_text(format_result_text(result))

# ===== MAIN =====
def main() -> int:
    """
    python3 scripts/analyze_run.py <OUT_DIR>
    """
    if len(sys.argv) != 2:
        print("ERROR: usage: python3 scripts/analyze_run.py <OUT_DIR>", file=sys.stderr)
        return 2

    out_dir = Path(sys.argv[1]).resolve()
    if not out_dir.exists():
        print(f"ERROR: OUT_DIR not found: {out_dir}", file=sys.stderr)
        return 2

    result = analyze(out_dir)
    write_outputs(out_dir, result)
    print(format_result_text(result).strip())
    return 0


