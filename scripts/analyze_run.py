def detect_wrong_trust_anchor_server_cert_case(out_dir: Path) -> Optional[Dict[str, Any]]:
    """
    Detects: TrustAnchorResolutionFailure > WrongTrustAnchorCase
    Direction: client verifies server
    Deterministic: No (log-based + cert count check)
    Evidence: client/handshake.txt
    """
    archetype = "TrustAnchorResolutionFailure"
    case = "WrongTrustAnchorCase"
    metadata = get_case_metadata(archetype, case)

    handshake = read_text(out_dir, "client/handshake.txt")

    # Check exclusions
    if check_exclusions(handshake, metadata["exclusions"]):
        return None

    # Check if it's actually missing intermediate (leaf-only)
    # Limitation: partial chains (leaf + some intermediates, but not all) have count > 1
    # and will be misclassified as WrongTrustAnchorCase rather than IncompleteChainFailure.
    presented_cert_text = read_text(out_dir, "inputs/server/fullchain.crt")
    if count_certificates(presented_cert_text) == 1:
        return None

    signal = first_regex_match(handshake, metadata["signals"])
    if not signal:
        return None

    # If it's explicitly the self-signed leaf, that is a different case.
    if re.search(r"self[- ]signed certificate", signal, flags=re.IGNORECASE):
        return None

    return build_failure_result(
        archetype,
        case,
        evidence_file="client/handshake.txt",
        failure_signal=signal,
        verifier="client",
        is_deterministic=False
    )


def detect_wrong_trust_anchor_client_cert_case(out_dir: Path) -> Optional[Dict[str, Any]]:
    """
    Detects: TrustAnchorResolutionFailure > WrongTrustAnchorCase
    Direction: server verifies client
    Deterministic: No (log-based + cert count check)
    Evidence: server/error.log
    """
    archetype = "TrustAnchorResolutionFailure"
    case = "WrongTrustAnchorCase"
    metadata = get_case_metadata(archetype, case)

    error_log = read_text(out_dir, "server/error.log")

    # Check exclusions
    if check_exclusions(error_log, metadata["exclusions"]):
        return None

    # Exclusion: BasicConstraints violation (CA:TRUE on client cert)
    # nginx may log "certificate verify failed" without "unsuitable certificate purpose"
    fields = read_text(out_dir, "certs/fields/client_cert.txt")
    if re.search(r"CA:TRUE", fields, flags=re.IGNORECASE):
        return None

    # Check if it's actually missing intermediate (leaf-only)
    # count == 0 means no client cert was presented;
    # count == 1 means leaf-only;
    # Limitation: partial chains (leaf + some intermediates, but not all) have count > 1
    # and will be misclassified as WrongTrustAnchorCase rather than IncompleteChainFailure.
    presented_cert_text = read_text(out_dir, "inputs/client/cert.crt")
    if count_certificates(presented_cert_text) == 1:
        return None

    signal = first_regex_match(error_log, metadata["signals"])
    if not signal:
        return None

    return build_failure_result(
        archetype,
        case,
        evidence_file="server/error.log",
        failure_signal=signal,
        verifier="server",
        is_deterministic=False
    )


