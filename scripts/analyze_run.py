def detect_basic_constraints_violation_case(out_dir: Path) -> Optional[Dict[str, Any]]:
    """
    Detects: UsageConstraintFailure > BasicConstraintsViolationCase
    Direction: server verifies client
    Deterministic: Yes (cert field inspection)
    Evidence: certs/fields/client_cert.txt
    """
    archetype = "UsageConstraintFailure"
    case = "BasicConstraintsViolationCase"
    metadata = get_case_metadata(archetype, case)

    fields = read_text(out_dir, metadata["evidence_file"])
    if not fields:
        return None

    has_basic_constraints = re.search(r"Basic Constraints", fields, flags=re.IGNORECASE)
    has_ca_true = re.search(r"CA:TRUE", fields, flags=re.IGNORECASE)

    if has_basic_constraints and has_ca_true:
        signal = "Basic Constraints indicates CA:TRUE on client credential"
        return build_failure_result(
            archetype,
            case,
            evidence_file=metadata["evidence_file"],
            failure_signal=signal,
            verifier="server",
            is_deterministic=True
        )

    return None


